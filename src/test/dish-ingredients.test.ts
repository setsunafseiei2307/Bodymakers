describe('料理の材料', () => {
  it('収録している料理がすべて表に載っている', () => {
    expect(Object.keys(EXPECTED).sort()).toEqual(DISHES.map((d) => d.id).sort());
  });

  it.each(DISHES.map((d) => [d.id, d] as const))(
    '%s の材料が意図した食品を指している',
    (id, dish) => {
      const expected = EXPECTED[id];
      expect(expected, `${id} が EXPECTED にありません`).toBeDefined();
      expect(dish.ingredients.length).toBe(expected.length);

      dish.ingredients.forEach((ingredient, index) => {
        const [foodId, name] = expected[index];
        expect(ingredient.foodId).toBe(foodId);
        const food = findFood(ingredient.foodId);
        expect(food, `食品番号 ${ingredient.foodId} が存在しません`).not.toBeNull();
        // ここが本題。番号を間違えると名前が変わる
        expect(food!.name, `食品番号 ${ingredient.foodId} の中身が変わりました`).toBe(name);
      });
    },
  );

  it('分量はすべて正の数', () => {
    for (const dish of DISHES) {
      for (const ingredient of dish.ingredients) {
        expect(ingredient.grams, `${dish.id}: ${ingredient.foodId}`).toBeGreaterThan(0);
      }
    }
  });

  /**
   * 素材から組めるものは素材から組む、という方針の確認。
   * 材料1つだけの料理は、調理済みの収載値を使っていることになるので、
   * その理由を画面に出せるよう composite を立てる必要がある。
   */
  it('材料が1〜2品しかない料理は、理由を添えている', () => {
    for (const dish of DISHES) {
      if (dish.ingredients.length <= 2 && dish.composite !== true) {
        // 素材が少なくても内訳として成立するものはある（卵と納豆など）ので、
        // 調理済みの収載食品（18xxx 調理済み流通食品類）を使うときだけ求める
        const usesPrepared = dish.ingredients.some((i) => i.foodId.startsWith('18'));
        expect(
          usesPrepared,
          `${dish.id}: 調理済み食品を使うなら composite: true と理由が必要です`,
        ).toBe(false);
      }
      if (dish.composite) {
        expect(dish.compositeNote, `${dish.id}: composite なら理由が必要です`).toBeTruthy();
      }
    }
  });

  it('カテゴリはすべて定義済みのもの', () => {
    for (const dish of DISHES) {
      expect(DISH_CATEGORIES).toContain(dish.category);
    }
  });

  it('カテゴリ分けにすべての料理が含まれる', () => {
    const grouped = dishesByCategory().flatMap((g) => g.dishes);
    expect(grouped.length).toBe(DISHES.length);
  });

  it('合計カロリーが計算でき、常識的な範囲に収まる', () => {
    for (const dish of DISHES) {
      const result = calcDish(dish);
      expect(result.totals.kcal, `${dish.id}`).toBeGreaterThan(100);
      expect(result.totals.kcal, `${dish.id}`).toBeLessThan(1500);
      // 内訳の行数は材料の数と一致する（欠測で行が消えていないこと）
      expect(result.rows.length).toBe(dish.ingredients.length);
    }
  });
});
